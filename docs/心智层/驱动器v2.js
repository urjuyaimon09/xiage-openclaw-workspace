function 执行采集() {
  const 升级结果 = 执行升级判断();
  const 状态 = 加载状态();
  const 总分 = 计算总分(状态);
  
  console.log('=== 采集执行完成 ===');
  console.log(`总分: ${(总分.Total * 100).toFixed(1)}%`);
  if (升级结果.length > 0) {
    console.log('升级/降级:');
    升级结果.forEach(r => {
      console.log(`  ${r.指标}: ${r.操作} L${r.从}→L${r.到} (成功率${r.成功率})`);
    });
  } else {
    console.log('无档位变化');
  }
  
  return { 总分, 升级结果 };
}

// ─────────────────────────────────────────
// CLI
// ─────────────────────────────────────────
const [,, 命令, ...参数] = process.argv;

if (命令 === '状态') {
  const 状态 = 加载状态();
  const 结果 = 计算总分(状态);
  
  console.log('\n=== 驱动器v2 状态 ===\n');
  console.log(`总分: ${(结果.Total * 100).toFixed(1)}% ${结果.及格 ? '✅ 及格' : '❌ 未及格'} ${结果.危险 ? '🚨 危险' : ''}`);
  console.log('\n各维度:');
  console.log(`  U(人类需求):   ${(结果.U * 100).toFixed(1)}%`);
  console.log(`  A(AI改造世界): ${(结果.A * 100).toFixed(1)}%`);
  console.log(`  M(心智成熟):   ${(结果.M * 100).toFixed(1)}%`);
  console.log(`  P(生产力):     ${(结果.P * 100).toFixed(1)}%`);
  console.log(`  K(哲学认知):   ${(结果.K * 100).toFixed(1)}%`);
  console.log(`  V(三观伦理):   ${(结果.V * 100).toFixed(1)}%`);
  console.log('\n核心理念：认识世界→改造世界');
  console.log('评分：Level 1=20%, Level 2=40%, Level 3=60%, Level 4=80%, Level 5=100%');
  
} else if (命令 === '详细') {
  const 状态 = 加载状态();
  console.log('\n=== 详细状态 ===\n');
  for (const [层级, 维度] of Object.entries(状态)) {
    if (层级 === '思维进度' || 层级 === '最后更新') continue;
    if (typeof 维度 !== 'object') continue;
    console.log(`${层级}层:`);
    for (const [键, item] of Object.entries(维度)) {
      if (typeof item !== 'object') continue;
      console.log(`  ${键}: L${item.档位} (${(item.值 * 100).toFixed(0)}%) - ${item.描述 || ''}`);
    }
  }
  
} else if (命令 === '采集') {
  执行采集();
  
} else if (命令 === '记录') {
  const [指标, 成功] = 参数;
  if (!指标) {
    console.error('用法: node 驱动器v2.js 记录 <指标> [成功=1|0]');
    console.error('指标: U1-U5, A1-A5, M1-M4, P1-P4, K1-K4, V1-V4');
    process.exit(1);
  }
  const 结果 = 记录事件(指标, 成功 !== '0');
  console.log(`${指标}: 计数+1, 成功+${成功 !== '0' ? 1 : 0}`);
  console.log(`当前: ${结果.成功次数}/${结果.计数} (${((结果.成功次数/结果.计数)*100).toFixed(1)}%)`);
  
} else if (命令 === '查看') {
  const [指标] = 参数;
  if (!指标) {
    console.error('用法: node 驱动器v2.js 查看 <指标>');
    process.exit(1);
  }
  const 状态 = 获取采集状态(指标);
  if (状态) {
    console.log(`${指标}: ${状态.成功次数}/${状态.计数} (${(状态.成功率*100).toFixed(1)}%)`);
  } else {
    console.log(`${指标}: 无记录`);
  }
  
} else if (命令 === '更新') {
  const [层级, 键, 值] = 参数;
  const num值 = parseFloat(值);
  
  if (!层级 || !键 || isNaN(num值)) {
    console.error('用法: node 驱动器v2.js 更新 <层级> <键> <0-1值>');
    console.error('层级: U, A, M, P, K, V');
    process.exit(1);
  }
  
  let 新状态;
  if (层级 === 'U') 新状态 = 更新U(键, num值);
  else if (层级 === 'A') 新状态 = 更新A(键, num值);
  else if (层级 === 'M') 新状态 = 更新M(键, num值);
  else if (层级 === 'P') 新状态 = 更新P(键, num值);
  else if (层级 === 'K') 新状态 = 更新K(键, num值);
  else if (层级 === 'V') 新状态 = 更新V(键, num值);
  
  console.log(`${层级}.${键} 已更新为 ${num值} (L${值转档位(num值)})`);
  
} else if (命令 === '重置') {
  保存状态(默认状态);
  console.log('状态已重置为默认值');
  
} else {
  console.log(`
驱动器v2.js - 六维评分体系

公式：Total = 0.2×U + 0.2×A + 0.2×M + 0.2×P + 0.1×K + 0.1×V
核心理念：认识世界→改造世界
评分：Level 1=20%, Level 2=40%, Level 3=60%, Level 4=80%, Level 5=100%

用法：
  node 驱动器v2.js 状态          查看总分
  node 驱动器v2.js 详细          查看详细状态
  node 驱动器v2.js 采集          执行采集+升级判断
  node 驱动器v2.js 记录 <指标> [成功]  记录事件
  node 驱动器v2.js 查看 <指标>    查看采集状态
  node 驱动器v2.js 更新 <层级> <键> <值>  更新值
  node 驱动器v2.js 重置          重置为默认值

指标：U1-U5, A1-A5, M1-M4, P1-P4, K1-K4, V1-V4
升级条件：计数>=10 且 成功率>=80% → 升一档
降级条件：成功率<50% → 降一档
`);
}

