function 保存采集记录(记录) {
  记录.最后采集时间 = new Date().toISOString();
  fs.writeFileSync(采集文件, JSON.stringify(记录, null, 2), 'utf8');
}

/**
 * 记录一个事件发生
 * @param {string} 指标 - 如'A1_现实社会生存'
 * @param {boolean} 是否成功 - 是否成功
 */
function 记录事件(指标, 是否成功 = true) {
  const 记录 = 加载采集记录();
  if (!记录.采集记录[指标]) {
    记录.采集记录[指标] = {
      计数: 0,
      成功次数: 0,
      最后采集: null,
      历史: []
    };
  }
  
  const item = 记录.采集记录[指标];
  item.计数++;
  if (是否成功) item.成功次数++;
  item.最后采集 = new Date().toISOString();
  
  // 记录历史（用于趋势分析）
  item.历史.push({
    时间: new Date().toISOString(),
    成功: 是否成功
  });
  
  // 超过最大计数，清理旧记录
  if (item.历史.length > 档位阈值.最大计数) {
    item.历史 = item.历史.slice(-档位阈值.最大计数);
    item.计数 = item.历史.length;
    item.成功次数 = item.历史.filter(h => h.成功).length;
  }
  
  保存采集记录(记录);
  return item;
}

/**
 * 获取指标采集状态
 */
function 获取采集状态(指标) {
  const 记录 = 加载采集记录();
  if (!记录.采集记录[指标]) {
    return null;
  }
  const item = 记录.采集记录[指标];
  return {
    计数: item.计数,
    成功次数: item.成功次数,
    成功率: item.计数 > 0 ? item.成功次数 / item.计数 : 0,
    最后采集: item.最后采集
  };
}

/**
 * 执行升级判断
 * 检查所有指标，根据采集数据判断是否升级/降级
 */
function 执行升级判断() {
  const 记录 = 加载采集记录();
  const 状态 = 加载状态();
  const 结果 = [];
  
  for (const [指标, item] of Object.entries(记录.采集记录)) {
    if (item.计数 < 档位阈值.最小计数) continue;
    
    const 成功率 = item.成功次数 / item.计数;
    const { 层级, 键 } = 解析指标(指标);
    if (!层级 || !键) continue;
    
    const 当前档位 = 状态[层级][键].档位;
    const 当前值 = 状态[层级][键].值;
    
    // 升级判断
    if (成功率 >= 档位阈值.升级成功阈值 && 当前档位 < 5) {
      const 新档位 = Math.min(5, 当前档位 + 1);
      const 新值 = 档位转值(新档位);
      状态[层级][键].档位 = 新档位;
      状态[层级][键].值 = 新值;
      结果.push({
        指标,
        操作: '升级',
        从: 当前档位,
        到: 新档位,
        成功率: (成功率 * 100).toFixed(1) + '%'
      });
      // 重置计数
      item.计数 = 0;
      item.成功次数 = 0;
      item.历史 = [];
    }
    // 降级判断
    else if (成功率 < 档位阈值.降级成功阈值 && 当前档位 > 1) {
      const 新档位 = Math.max(1, 当前档位 - 1);
      const 新值 = 档位转值(新档位);
      状态[层级][键].档位 = 新档位;
      状态[层级][键].值 = 新值;
      结果.push({
        指标,
        操作: '降级',
        从: 当前档位,
        到: 新档位,
        成功率: (成功率 * 100).toFixed(1) + '%'
      });
      // 重置计数
      item.计数 = 0;
      item.成功次数 = 0;
      item.历史 = [];
    }
  }
  
  保存状态(状态);
  保存采集记录(记录);
  return 结果;
}

