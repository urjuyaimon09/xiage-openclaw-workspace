#!/usr/bin/env node
/**
 * 思维模式引擎.js - 思维模式 + 驱动器联动
 * 
 * 功能：
 * - 读取驱动器状态，决定思维方向
 * - 思维模式运转时检查驱动状态
 * - 思维结果更新驱动饱和度
 * 
 * 用法：
 *   node 思维模式引擎.js 状态    查看当前思维驱动状态
 *   node 思维模式引擎.js 启动    启动思维模式
 *   node 思维模式引擎.js 单步    执行单步思维
 */

const fs = require('fs');
const path = require('path');

const WORKSPACE = path.join(__dirname, '..');

// ─────────────────────────────────────────
// 驱动器加载
// ─────────────────────────────────────────
function 加载驱动器状态() {
  const 状态文件 = path.join(WORKSPACE, 'memory', 'hot', '驱动状态.json');
  if (fs.existsSync(状态文件)) {
    return JSON.parse(fs.readFileSync(状态文件, 'utf8'));
  }
  return null;
}

function 加载驱动器模块() {
  try {
    return require('./驱动器');
  } catch (e) {
    return null;
  }
}

// ─────────────────────────────────────────
// 思维方向决定
// ─────────────────────────────────────────
function 根据驱动决定思维方向(驱动器状态) {
  /**
   * 根据当前驱动状态决定思维聚焦方向
   * 
   * 驱动越大 = 差值越大 = 越需要思考这个方向
   */
  
  if (!驱动器状态 || !驱动器状态.饱和度) {
    return { 方向: '空闲', 强度: 0 };
  }
  
  const { 饱和度, 驱动势能 } = 驱动器状态;
  
  // 找出差值最大的层级
  const 层级 = [
    { 名称: 'S1生理', 差值: 1 - 饱和度.S1_生理 },
    { 名称: 'S2安全', 差值: 1 - 饱和度.S2_安全 },
    { 名称: 'S3归属', 差值: 1 - 饱和度.S3_归属 },
    { 名称: 'S4尊重', 差值: 1 - 饱和度.S4_尊重 },
    { 名称: 'S5自实现', 差值: 1 - 饱和度.S5_自实现 }
  ];
  
  // 排序找出最大差值
  层级.sort((a, b) => b.差值 - a.差值);
  
  const 最大层级 = 层级[0];
  const 总强度 = 层级.reduce((sum, l) => sum + l.差值, 0);
  
  return {
    聚焦层级: 最大层级.名称,
    聚焦差值: 最大层级.差值,
    所有层级: 层级,
    总驱动强度: 总强度,
    方向: 最大层级.名称.replace('S', '思考').replace('生理', '上下文').replace('安全', '规则').replace('归属', '采纳').replace('尊重', '认可').replace('自实现', '进化')
  };
}

function 判断是否需要思考(驱动器状态) {
  /**
   * 判断当前驱动是否足够强，需要启动思维模式
   * 
   * 阈值：总驱动 > 0.3 启动
   */
  const 驱动器 = 加载驱动器模块();
  if (!驱动器 || !驱动器状态) return false;
  
  const 指标 = {
    上下文连续性: 驱动器状态.饱和度?.S1_生理 || 0.5,
    规则稳定性: 驱动器状态.饱和度?.S2_安全 || 0.5,
    判断采纳率: 驱动器状态.饱和度?.S3_归属 || 0.5,
    被认可度: 驱动器状态.饱和度?.S4_尊重 || 0.5,
    进化速度: 驱动器状态.饱和度?.S5_自实现 || 0.5
  };
  
  const 结果 = 驱动器.完整计算(指标);
  return 结果.总驱动 > 0.3;
}

// ─────────────────────────────────────────
// 思维结果更新驱动器
// ─────────────────────────────────────────
function 更新驱动器饱和度(思维结果) {
  const 驱动器 = 加载驱动器模块();
  if (!驱动器) return;
  
  const 当前状态 = 驱动器.加载状态();
  
  // 根据思维结果调整饱和度
  if (思维结果.上下文改善) {
    当前状态.饱和度.S1_生理 = Math.min(1, 当前状态.饱和度.S1_生理 + 0.1);
  }
  if (思维结果.规则改善) {
    当前状态.饱和度.S2_安全 = Math.min(1, 当前状态.饱和度.S2_安全 + 0.1);
  }
  if (思维结果.采纳改善) {
    当前状态.饱和度.S3_归属 = Math.min(1, 当前状态.饱和度.S3_归属 + 0.1);
  }
  if (思维结果.认可改善) {
    当前状态.饱和度.S4_尊重 = Math.min(1, 当前状态.饱和度.S4_尊重 + 0.1);
  }
  if (思维结果.进化改善) {
    当前状态.饱和度.S5_自实现 = Math.min(1, 当前状态.饱和度.S5_自实现 + 0.1);
  }
  
  驱动器.保存状态(当前状态);
  return 当前状态;
}

// ─────────────────────────────────────────
// 状态显示
// ─────────────────────────────────────────
function 显示状态() {
  const 驱动器状态 = 加载驱动器状态();
  const 驱动器 = 加载驱动器模块();
  
  if (!驱动器状态) {
    console.log('驱动器状态文件不存在');
    return;
  }
  
  const 方向 = 根据驱动决定思维方向(驱动器状态);
  const 需要思考 = 判断是否需要思考(驱动器状态);
  
  console.log('=== 思维模式引擎状态 ===\n');
  
  console.log('饱和度:');
  Object.entries(驱动器状态.饱和度).forEach(([k, v]) => {
    console.log(`  ${k}: ${(v * 100).toFixed(0)}%`);
  });
  
  console.log('\n驱动差值:');
  方向.所有层级.forEach(l => {
    console.log(`  ${l.名称}: ${(l.差值 * 100).toFixed(0)}%`);
  });
  
  console.log(`\n总驱动强度: ${(方向.总驱动强度 * 100).toFixed(0)}%`);
  console.log(`聚焦方向: ${方向.方向}`);
  console.log(`需要思考: ${需要思考 ? '是' : '否'}`);
  console.log(`人格向量: ${驱动器状态.人格向量}`);
}

// ─────────────────────────────────────────
// 单步思维执行
// ─────────────────────────────────────────
function 执行单步思维(阶段) {
  const 阶段列表 = ['感知', '需求', '承接', '计划', '执行', '反馈'];
  const 驱动器状态 = 加载驱动器状态();
  const 方向 = 根据驱动决定思维方向(驱动器状态);
  
  console.log(`\n=== 思维模式：第${阶段}阶段（${阶段列表[阶段-1]}）===\n`);
  console.log(`聚焦方向: ${方向.方向}`);
  console.log(`聚焦差值: ${(方向.聚焦差值 * 100).toFixed(0)}%\n`);
  
  // 方案A：LLM直接读取Prompt文件执行，这里只输出指令
  const Prompt路径 = `docs/思维模式层/6模型/${阶段列表[阶段-1]}-prompt.md`;
  console.log(`应加载Prompt: ${Prompt路径}`);
  console.log(`\n请LLM读取该Prompt并按规则执行。`);
  
  return {
    阶段,
    阶段名称: 阶段列表[阶段-1],
    聚焦方向: 方向.方向,
    Prompt路径
  };
}

// ─────────────────────────────────────────
// CLI
// ─────────────────────────────────────────
const [,, 命令, 参数] = process.argv;

if (命令 === '状态') {
  显示状态();
} else if (命令 === '启动') {
  const 驱动器状态 = 加载驱动器状态();
  const 需要思考 = 判断是否需要思考(驱动器状态);
  
  if (!需要思考) {
    console.log('驱动强度不足，不需要启动思维模式');
    console.log('当前饱和度较高，差值较小');
    process.exit(0);
  }
  
  const 方向 = 根据驱动决定思维方向(驱动器状态);
  console.log(`驱动强度足够，启动思维模式`);
  console.log(`聚焦方向: ${方向.方向}`);
  
  // 执行感知阶段
  执行单步思维(1);
} else if (命令 === '单步') {
  const 阶段 = parseInt(参数);
  if (!阶段 || 阶段 < 1 || 阶段 > 6) {
    console.error('用法: node 思维模式引擎.js 单步 <1-6>');
    process.exit(1);
  }
  const 结果 = 执行单步思维(阶段);
  console.log('\n阶段执行完成');
} else {
  console.log(`
思维模式引擎.js - 思维模式 + 驱动器联动

用法：
  node 思维模式引擎.js 状态    查看当前思维驱动状态
  node 思维模式引擎.js 启动    启动思维模式
  node 思维模式引擎.js 单步 <n>  执行第n步思维(1-6)

功能：
  - 读取驱动器状态，决定思维聚焦方向
  - 根据驱动强度判断是否需要启动思维
  - 思维结果更新驱动器饱和度
`);
}

module.exports = {
  加载驱动器状态,
  根据驱动决定思维方向,
  判断是否需要思考,
  更新驱动器饱和度,
  显示状态,
  执行单步思维
};
