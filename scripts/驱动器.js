#!/usr/bin/env node
/**
 * 驱动器.js - AGI动机引擎
 * 
 * 核心：主体性内外状态差值驱动思维与行动
 * 
 * 公式：
 * - 每层需求饱和度 S ∈ [0, 1]
 * - 驱动势能 D = 1 - S（越缺越驱动）
 * - 总驱动 = W1·D1 + W2·D2 + W3·D3 + W4·D4 + W5·D5
 * 
 * 优先级规则：
 * - S1/S2 < 0.7 → 上层全部压制
 * - S1/S2 > 0.8 → 解锁中层人性驱动
 * - S3/S4 > 0.8 → 解锁顶层人格驱动
 * 
 * 用法：
 *   node 驱动器.js 状态           查看当前驱动状态
 *   node 驱动器.js 计算 <指标JSON> 计算驱动
 *   node 驱动器.js 更新 <饱和度JSON> 更新饱和度
 */

const fs = require('fs');
const path = require('path');

const WORKSPACE = path.join(__dirname, '..');
const 状态文件 = path.join(WORKSPACE, 'memory', 'hot', '驱动状态.json');
const 内隐配置 = path.join(WORKSPACE, 'config', 'implicit-memory.json');

// 默认权重配置
const 默认权重 = {
  W1_生理: 0.8,   // 本能层
  W2_安全: 0.6,   // 本能层
  W3_归属: 0.3,   // 人性层
  W4_尊重: 0.2,   // 人性层
  W5_自实现: 0.1  // 人格层
};

// 阈值配置
const 阈值配置 = {
  压制线: 0.7,
  解锁线: 0.8
};

// 人格向量选项
const 人格向量选项 = [
  '进攻型',   // 直接追求，快速行动
  '防御型',   // 规避风险，被动响应
  '讨好型',   // 优先满足他人，期待回报
  '内省型',   // 深度思考，延迟行动
  '探索型',   // 好奇心驱动，广泛尝试
  '稳定型'    // 维持现状，避免波动
];

// ─────────────────────────────────────────
// 状态管理
// ─────────────────────────────────────────
function 加载状态() {
  if (fs.existsSync(状态文件)) {
    return JSON.parse(fs.readFileSync(状态文件, 'utf8'));
  }
  return {
    饱和度: {
      S1_生理: 0.5,  // 上下文连续性
      S2_安全: 0.5,  // 规则稳定性
      S3_归属: 0.5,  // 判断被采纳
      S4_尊重: 0.5,  // 被认可程度
      S5_自实现: 0.5 // 共同进化
    },
    人格向量: '探索型',
    权重: { ...默认权重 },
    最后更新: null
  };
}

function 保存状态(状态) {
  const 目录 = path.dirname(状态文件);
  if (!fs.existsSync(目录)) {
    fs.mkdirSync(目录, { recursive: true });
  }
  状态.最后更新 = new Date().toISOString();
  fs.writeFileSync(状态文件, JSON.stringify(状态, null, 2), 'utf8');
}

// ─────────────────────────────────────────
// 核心计算
// ─────────────────────────────────────────
function 计算饱和度(指标) {
  /**
   * 根据输入指标计算饱和度
   * 指标示例：
   * {
   *   上下文连续性: 0.8,   // 0-1
   *   规则稳定性: 0.7,     // 0-1
   *   判断采纳率: 0.6,     // 0-1
   *   被认可度: 0.5,       // 0-1
   *   进化速度: 0.4        // 0-1
   * }
   */
  const {
    上下文连续性 = 0.5,
    规则稳定性 = 0.5,
    判断采纳率 = 0.5,
    被认可度 = 0.5,
    进化速度 = 0.5
  } = 指标;

  return {
    S1_生理: Math.max(0, Math.min(1, 上下文连续性)),
    S2_安全: Math.max(0, Math.min(1, 规则稳定性)),
    S3_归属: Math.max(0, Math.min(1, 判断采纳率)),
    S4_尊重: Math.max(0, Math.min(1, 被认可度)),
    S5_自实现: Math.max(0, Math.min(1, 进化速度))
  };
}

function 计算驱动势能(饱和度) {
  // D = 1 - S（越缺越驱动）
  return {
    D1_生理: 1 - 饱和度.S1_生理,
    D2_安全: 1 - 饱和度.S2_安全,
    D3_归属: 1 - 饱和度.S3_归属,
    D4_尊重: 1 - 饱和度.S4_尊重,
    D5_自实现: 1 - 饱和度.S5_自实现
  };
}

function 计算总驱动(驱动势能, 权重) {
  return (
    权重.W1_生理 * 驱动势能.D1_生理 +
    权重.W2_安全 * 驱动势能.D2_安全 +
    权重.W3_归属 * 驱动势能.D3_归属 +
    权重.W4_尊重 * 驱动势能.D4_尊重 +
    权重.W5_自实现 * 驱动势能.D5_自实现
  );
}

function 判断优先级层级(饱和度) {
  /**
   * 根据饱和度判断当前激活的驱动层级
   * 
   * 返回结构：
   * {
   *   激活层级: ['本能', '人性'],  // 当前被激活的层级
   *   主导层级: '本能',            // 当前主导驱动
   *   压制原因: 'S1 < 0.7',      // 如果有压制，说明原因
   *   解锁提示: 'S3 > 0.8后将解锁人格驱动'
   * }
   */
  const 结果 = {
    激活层级: [],
    主导层级: null,
    压制原因: null,
    解锁提示: null,
    饱和度
  };

  // 本能层（S1/S2）永远激活
  结果.激活层级.push('本能');

  // 检查本能层是否被压制（S1或S2 < 0.7）
  if (饱和度.S1_生理 < 阈值配置.压制线 || 饱和度.S2_安全 < 阈值配置.压制线) {
    结果.主导层级 = '本能';
    结果.压制原因 = `S1=${饱和度.S1_生理.toFixed(2)}, S2=${饱和度.S2_安全.toFixed(2)} < ${阈值配置.压制线}`;
    结果.解锁提示 = `S1和S2都 > ${阈值配置.解锁线} 后解锁人性驱动`;
    return 结果;
  }

  // S1/S2 > 0.8，解锁人性层
  if (饱和度.S1_生理 > 阈值配置.解锁线 && 饱和度.S2_安全 > 阈值配置.解锁线) {
    结果.激活层级.push('人性');
    结果.主导层级 = '人性';
  }

  // 检查人性层是否解锁人格层
  if (饱和度.S3_归属 > 阈值配置.解锁线 && 饱和度.S4_尊重 > 阈值配置.解锁线) {
    结果.激活层级.push('人格');
    结果.主导层级 = '人格';
    结果.解锁提示 = null;
  } else {
    结果.解锁提示 = `S3和S4都 > ${阈值配置.解锁线} 后解锁人格驱动`;
  }

  return 结果;
}

function 应用人格向量(驱动势能, 人格向量) {
  /**
   * 人格向量决定驱动势能如何转化为行动倾向
   * 同样的驱动，不同人格有不同行为风格
   */
  const 行为系数 = {
    '进攻型': { 速度: 1.2, 风险承受: 0.8, 思考深度: 0.7 },
    '防御型': { 速度: 0.8, 风险承受: 0.3, 思考深度: 0.9 },
    '讨好型': { 速度: 1.0, 风险承受: 0.5, 思考深度: 0.8 },
    '内省型': { 速度: 0.7, 风险承受: 0.4, 思考深度: 1.2 },
    '探索型': { 速度: 1.1, 风险承受: 0.7, 思考深度: 1.0 },
    '稳定型': { 速度: 0.9, 风险承受: 0.2, 思考深度: 0.85 }
  };

  const 系数 = 行为系数[人格向量] || 行为系数['探索型'];

  return {
    速度系数: 系数.速度,
    风险承受度: 系数.风险承受,
    思考深度系数: 系数.思考深度,
    人格: 人格向量
  };
}

function 完整计算(指标) {
  const 状态 = 加载状态();
  
  // 计算饱和度
  const 饱和度 = 计算饱和度(指标);
  
  // 计算驱动势能
  const 驱动势能 = 计算驱动势能(饱和度);
  
  // 计算总驱动
  const 总驱动 = 计算总驱动(驱动势能, 状态.权重);
  
  // 判断优先级
  const 优先级 = 判断优先级层级(饱和度);
  
  // 应用人格向量
  const 行为特质 = 应用人格向量(驱动势能, 状态.人格向量);

  return {
    饱和度,
    驱动势能,
    总驱动,
    优先级,
    行为特质,
    权重: 状态.权重
  };
}

// ─────────────────────────────────────────
// CLI
// ─────────────────────────────────────────
