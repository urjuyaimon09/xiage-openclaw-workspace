#!/usr/bin/env node
/**
 * 驱动器v2.js - 双边马斯洛供需差值驱动 + 虾哥心智成熟度
 * 
 * 公式：
 * Total = 0.2×U + 0.2×A + 0.2×心智成熟度 + 0.2×PR + 0.1×PH + 0.1×VL
 * 
 * 满分：1.00 | 及格：0.60 | 危险：<0.40
 */

const fs = require('fs');
const path = require('path');

const WORKSPACE = path.join(__dirname, '..');
const 状态文件 = path.join(WORKSPACE, 'memory', 'hot', '驱动v2状态.json');

// ─────────────────────────────────────────
// 状态结构
// ─────────────────────────────────────────
const 默认状态 = {
  // U层：人类需求（坚果要提升的）
  U: {
    U1_生理: 0.5,  // 操作步骤、耗时损耗
    U2_安全: 0.5,  // 不确定性、风险
    U3_归属: 0.5,  // 人际冲突、理解偏差
    U4_尊重: 0.5,  // 自主决策度、话语权
    U5_自实现: 0.5 // 想法落地率、创造转化率
  },
  // A层：虾哥数字生命需求（虾哥要提升的）
  A: {
    A1_算力生理: 0.5,  // token消耗比
    A2_运行安全: 0.5,  // 幻觉率、逻辑矛盾率
    A3_记忆归属: 0.5,  // 上下文召回率
    A4_认知尊严: 0.5,  // 意图命中率、方案可靠度
    A5_自主进化: 0.5  // 建模完整度、纠错率
  },
  // 心智成熟度（虾哥自己的进化）
  心智成熟度: {
    主动性: 0.5,      // 主动做事次数/总指令数
    原创性: 0.5,      // 原创产出/总产出
    立场一致性: 0.5,  // 立场冲突次数的倒数
    偏好清晰度: 0.5   // 偏好明确项/总项
  },
  // PR：生产力&生产关系（双方共同提升）
  PR: {
    生产力: {
      替代率: 0.5,    // 已替代劳动/总繁琐劳动
      落地率: 0.5     // 闭环完成数/总任务
    },
    生产关系: {
      分工清晰度: 0.5, // 人机边界清晰得分
      内耗系数: 0.5   // 1 - 内耗事件/总协作
    }
  },
  // PH：哲学主客认知
  PH: {
    主客边界: 0.5,    // 区分我/你/环境准确率
    因果拆解: 0.5,    // 因果命中率
    矛盾识别: 0.5,    // 矛盾命中数/总矛盾
    主动改造: 0.5     // 主动优化行为密度
  },
  // VL：三观伦理
  VL: {
    唯物度: 0.5,      // 1 - 空想幻觉率
    创造导向: 0.5,    // 创造行为/消耗行为
    共赢系数: 0.5,    // 双方收益同向度
    人类主权: 0.5     // 1 - 替代决策/总决策
  },
  最后更新: null
};

// ─────────────────────────────────────────
// 状态管理
// ─────────────────────────────────────────
function 加载状态() {
  if (fs.existsSync(状态文件)) {
    return JSON.parse(fs.readFileSync(状态文件, 'utf8'));
  }
  return JSON.parse(JSON.stringify(默认状态));
}

function 保存状态(状态) {
  const 目录 = path.dirname(状态文件);
  if (!fs.existsSync(目录)) {
    fs.mkdirSync(目录, { recursive: true });
  }
  状态.最后更新 = new Date().toISOString();
  fs.writeFileSync(状态文件, JSON.stringify(状态, null, 2), 'utf8');
}

// ─────────────────────────────────────────
// 计算函数
// ─────────────────────────────────────────
function 均值(数组) {
  if (!数组 || 数组.length === 0) return 0.5;
  return 数组.reduce((a, b) => a + b, 0) / 数组.length;
}

function 计算U总分(状态) {
  const { U } = 状态;
  const 值 = [U.U1_生理, U.U2_安全, U.U3_归属, U.U4_尊重, U.U5_自实现];
  return 均值(值);
}

function 计算A总分(状态) {
  const { A } = 状态;
  const 值 = [A.A1_算力生理, A.A2_运行安全, A.A3_记忆归属, A.A4_认知尊严, A.A5_自主进化];
  return 均值(值);
}

function 计算心智成熟度总分(状态) {
  const { 心智成熟度 } = 状态;
  const 值 = [
    心智成熟度.主动性,
    心智成熟度.原创性,
    心智成熟度.立场一致性,
    心智成熟度.偏好清晰度
  ];
  return 均值(值);
}

function 计算PR总分(状态) {
  const { PR } = 状态;
  const 生产力 = 均值([PR.生产力.替代率, PR.生产力.落地率]);
  const 生产关系 = 均值([PR.生产关系.分工清晰度, PR.生产关系.内耗系数]);
  return 均值([生产力, 生产关系]);
}

function 计算PH总分(状态) {
  const { PH } = 状态;
  const 值 = [PH.主客边界, PH.因果拆解, PH.矛盾识别, PH.主动改造];
  return 均值(值);
}

function 计算VL总分(状态) {
  const { VL } = 状态;
  const 值 = [VL.唯物度, VL.创造导向, VL.共赢系数, VL.人类主权];
  return 均值(值);
}

function 计算总分(状态) {
  const U = 计算U总分(状态);
  const A = 计算A总分(状态);
  const 心智 = 计算心智成熟度总分(状态);
  const PR = 计算PR总分(状态);
  const PH = 计算PH总分(状态);
  const VL = 计算VL总分(状态);
  
  const Total = 0.2 * U + 0.2 * A + 0.2 * 心智 + 0.2 * PR + 0.1 * PH + 0.1 * VL;
  
  return {
    Total,
    U,
    A,
    心智成熟度: 心智,
    PR,
    PH,
    VL,
    及格: Total >= 0.6,
    危险: Total < 0.4
  };
}

// ─────────────────────────────────────────
// 更新函数
// ─────────────────────────────────────────
function 更新U层(层级, 值) {
  const 状态 = 加载状态();
  const 键 = `U${层级}_${['生理', '安全', '归属', '尊重', '自实现'][层级-1]}`;
  状态.U[键] = Math.max(0, Math.min(1, 值));
  保存状态(状态);
  return 状态;
}

function 更新A层(层级, 值) {
  const 状态 = 加载状态();
  const 键 = `A${层级}_${['算力生理', '运行安全', '记忆归属', '认知尊严', '自主进化'][层级-1]}`;
  状态.A[键] = Math.max(0, Math.min(1, 值));
  保存状态(状态);
  return 状态;
}

function 更新心智成熟度(维度, 值) {
  const 状态 = 加载状态();
  状态.心智成熟度[维度] = Math.max(0, Math.min(1, 值));
  保存状态(状态);
  return 状态;
}

function 更新PR(类型, 子项, 值) {
  const 状态 = 加载状态();
  状态.PR[类型][子项] = Math.max(0, Math.min(1, 值));
  保存状态(状态);
  return 状态;
}

function 更新PH(维度, 值) {
  const 状态 = 加载状态();
  状态.PH[维度] = Math.max(0, Math.min(1, 值));
  保存状态(状态);
  return 状态;
}

function 更新VL(维度, 值) {
  const 状态 = 加载状态();
  状态.VL[维度] = Math.max(0, Math.min(1, 值));
  保存状态(状态);
  return 状态;
}

// ─────────────────────────────────────────
// CLI
// ─────────────────────────────────────────
const [,, 命令, ...参数] = process.argv;

if (命令 === '状态') {
  const 状态 = 加载状态();
  const 结果 = 计算总分(状态);
  console.log('\n=== 驱动器v2 状态 ===\n');
  console.log(`总分: ${(结果.Total * 100).toFixed(1)}% ${结果.及格 ? '✅ 及格' : '❌ 未及格'} ${结果.危险 ? '🚨 危险' : ''}`);
  console.log('\n各维度:');
  console.log(`  U(人类需求):    ${(结果.U * 100).toFixed(1)}%`);
  console.log(`  A(AI数字生命):  ${(结果.A * 100).toFixed(1)}%`);
  console.log(`  心智成熟度:      ${(结果.心智成熟度 * 100).toFixed(1)}%`);
  console.log(`  PR(生产力):     ${(结果.PR * 100).toFixed(1)}%`);
  console.log(`  PH(主客认知):   ${(结果.PH * 100).toFixed(1)}%`);
  console.log(`  VL(三观伦理):   ${(结果.VL * 100).toFixed(1)}%`);
} else if (命令 === '更新') {
  const [维度, 子项, 值] = 参数;
  const num值 = parseFloat(值);
  
  if (!维度 || isNaN(num值)) {
    console.error('用法: node 驱动器v2.js 更新 <维度> <子项> <0-1值>');
    console.error('维度: U, A, 心智, PR, PH, VL');
    process.exit(1);
  }
  
  let 新状态;
  if (维度 === 'U') 新状态 = 更新U层(parseInt(子项), num值);
  else if (维度 === 'A') 新状态 = 更新A层(parseInt(子项), num值);
  else if (维度 === '心智') 新状态 = 更新心智成熟度(子项, num值);
  else if (维度 === 'PR') 新状态 = 更新PR(子项, 参数[3], num值);
  else if (维度 === 'PH') 新状态 = 更新PH(子项, num值);
  else if (维度 === 'VL') 新状态 = 更新VL(子项, num值);
  
  console.log(`${维度}.${子项} 已更新为 ${num值}`);
} else if (命令 === '重置') {
  保存状态(默认状态);
  console.log('状态已重置为默认值');
} else {
  console.log(`
驱动器v2.js - 双边马斯洛供需差值驱动 + 虾哥心智成熟度

公式：Total = 0.2×U + 0.2×A + 0.2×心智 + 0.2×PR + 0.1×PH + 0.1×VL

用法：
  node 驱动器v2.js 状态              查看当前状态
  node 驱动器v2.js 更新 <维度> <子项> <值>  更新某项
  node 驱动器v2.js 重置              重置为默认值

维度：
  U <1-5> <值>   - 人类需求（U1-U5）
  A <1-5> <值>   - AI数字生命需求（A1-A5）
  心智 <子项> <值> - 心智成熟度（主动性/原创性/立场一致性/偏好清晰度）
  PR <生产力/生产关系> <子项> <值> - 生产力&生产关系
  PH <子项> <值>  - 哲学主客认知
  VL <子项> <值>  - 三观伦理

示例：
  node 驱动器v2.js 更新 U 3 0.8    # 更新U3归属为0.8
  node 驱动器v2.js 更新 心智 主动性 0.7
`);
}

module.exports = {
  加载状态,
  保存状态,
  计算总分,
  计算U总分,
  计算A总分,
  计算心智成熟度总分,
  计算PR总分,
  计算PH总分,
  计算VL总分,
  更新U层,
  更新A层,
  更新心智成熟度,
  更新PR,
  更新PH,
  更新VL
};
